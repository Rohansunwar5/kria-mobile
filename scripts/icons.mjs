// Regenerates src/components/ui/iconPaths.ts from Google's Material Symbols
// (Outlined). Add a name below and run `node scripts/icons.mjs`.
//   o = wght 300 outline (default), f = FILL 1 (active nav), b = wght 500.
import { writeFileSync } from 'fs';

const ICONS = {
  home: 'of', leaderboard: 'of', stadium: 'of', military_tech: 'of',
  add: 'ob', pin: 'ob', check: 'ob',
  expand_more: 'o', chevron_right: 'o', location_on: 'o', refresh: 'o',
  // Filled variants are the award badge glyphs (AwardBadge: FILL 1).
  sports_tennis: 'of', sports_cricket: 'of', table_restaurant: 'of', sports_soccer: 'of',
  sports_kabaddi: 'of', sports: 'of', emoji_events: 'of', workspace_premium: 'o',
  qr_code_2: 'o', person_check: 'o', trending_up: 'o',
  arrow_back: 'o', close: 'o', ios_share: 'o', content_copy: 'o', info: 'o', swipe_vertical: 'o',
  undo: 'o', block: 'o', edit: 'o', remove: 'o', error: 'o', search: 'o', more_horiz: 'o',
  gavel: 'o', settings: 'o', photo_camera: 'o', logout: 'o', receipt_long: 'o', assignment: 'o', push_pin: 'o', forum: 'o', campaign: 'o', account_tree: 'o', sensors: 'o',
  sports_baseball: 'o',
};
const VARIANT = { o: 'wght300', f: 'fill1', b: 'wght500' };
const base = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined';

const out = {};
for (const [name, variants] of Object.entries(ICONS)) {
  out[name] = {};
  for (const v of variants) {
    const svg = await (await fetch(`${base}/${name}/${VARIANT[v]}/24px.svg`)).text();
    const d = svg.match(/ d="([^"]+)"/)?.[1];
    if (!d) throw new Error(`${name}/${VARIANT[v]}: no path`);
    out[name][v] = d;
  }
}

writeFileSync(
  'src/components/ui/iconPaths.ts',
  `// Generated by scripts/icons.mjs — do not edit by hand. viewBox 0 -960 960 960.\n` +
    `export const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;\n\n` +
    `export type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`${Object.keys(out).length} icons written`);
